//go:build unit

package service

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestCollabWorkerResolution(t *testing.T) {
	for _, tc := range []struct {
		name, source string
		unsafe       bool
	}{
		{"parameter", "package p; func task(){defer RecoverCollabWorker()}; func start(task func()){go task()}", true},
		{"selector_plain", "package p; func task(){defer RecoverCollabWorker()}; func start(){go x.task()}", true},
		{"identifier_method", "package p; type worker int; func (worker) task(){defer RecoverCollabWorker()}; func start(){go task()}", true},
		{"named_result", "package p; func task(){defer RecoverCollabWorker()}; func start()(task func()){go task(); return}", true},
		{"receiver", "package p; type worker int; func task(){defer RecoverCollabWorker()}; func (task worker) start(){go task()}", true},
		{"local_value", "package p; func task(){defer RecoverCollabWorker()}; func start(){task:=other;go task()}", true},
		{"reassigned", "package p; func start(){task:=func(){defer RecoverCollabWorker()}; task=other;go task()}", true},
		{"nested_parameter", "package p; func start(){task:=func(){defer RecoverCollabWorker()};func(task func()){go task()}(task)}", true},
		{"plain", "package p; func task(){defer RecoverCollabWorker()}; func start(){go task()}", false},
		{"method", "package p; type worker int; func (worker) task(){defer RecoverCollabWorker()}; func start(){go x.task()}", false},
		{"literal", "package p; func start(){task:=func(){defer RecoverCollabWorker()};go task()}", false},
		{"variable_literal", "package p; func start(){var task=func(){defer RecoverCollabWorker()};go task()}", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			require.NoError(t, os.WriteFile(filepath.Join(root, "fixture.go"), []byte(tc.source), 0600))
			audit, err := auditCollabWorkers([]string{root}, nil)
			require.NoError(t, err)
			require.Equal(t, 1, audit.checked)
			if tc.unsafe {
				require.Len(t, audit.failures, 1)
				require.Contains(t, audit.failures[0], "fixture.go:start")
			} else {
				require.Empty(t, audit.failures)
			}
		})
	}
}

func TestCollabWorkerRecursiveDiscovery(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"root.go":            "package p; func start(){go func(){defer RecoverCollabWorker()}()}",
		"child/worker.go":    "package child; func start(){go func(){}()}",
		"child/generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage child;func generated(){go func(){}()}",
		"testdata/skip.go":   "package fixture;func skip(){go func(){}()}",
		"child/skip_test.go": "package child;func test(){go func(){}()}",
	}
	for path, source := range files {
		path = filepath.Join(root, path)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0700))
		require.NoError(t, os.WriteFile(path, []byte(source), 0600))
	}
	audit, err := auditCollabWorkers([]string{root}, nil)
	require.NoError(t, err)
	require.Equal(t, 2, audit.files)
	require.Equal(t, 2, audit.checked)
	require.Len(t, audit.failures, 1)
	require.True(t, strings.Contains(audit.failures[0], "child/worker.go:start"))
}
